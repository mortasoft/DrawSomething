const ENYE_SENTINEL = '\uE000';
export const MIN_WORD_LENGTH = 2;
export const MAX_WORD_LENGTH = SCRABBLE_RACK_SIZE;
const DISPLAY_WORD_REGEX = /^[A-Za-zÁÉÍÓÚÜÑáéíóúüñ]+$/;

/**
 * Normalizes a word for Scrabble tiles and guess comparison while preserving Ñ.
 */
export function normalizeWord(raw: string): string {
  return raw
    .trim()
    .toUpperCase()
    .replace(/Ñ/g, ENYE_SENTINEL)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(new RegExp(ENYE_SENTINEL, 'g'), 'Ñ')
    .replace(/[^A-ZÑ]/g, '');
}

/**
 * Returns the base point value for a word difficulty.
 */
export function getPointsForDifficulty(difficulty: WordDifficulty): number {
  return difficulty === 'easy' ? 100 : 200;
}

/**
 * Formats a display word in uppercase while preserving Spanish accents and Ñ.
 */
export function formatDisplayWord(raw: string): string {
  return raw.trim().toLocaleUpperCase('es-ES');
}

export interface ValidatedWordValue {
  word: string;
  normalized: string;
  category: string;
  language: Language;
  difficulty: WordDifficulty;
  points: number;
}

/**
 * Validates and normalizes word creation/update input.
 */
export function validateWordInput(
  input: Partial<WordInput>
): { ok: true; value: ValidatedWordValue } | { ok: false; error: string } {
  const language = input.language;
  if (language !== 'es' && language !== 'en') {
    return { ok: false, error: 'Idioma inválido. Usa "es" o "en".' };
  }

  const difficulty = input.difficulty;
  if (difficulty !== 'easy' && difficulty !== 'hard') {
    return { ok: false, error: 'Dificultad inválida. Usa "easy" o "hard".' };
  }

  const rawWord = typeof input.word === 'string' ? input.word.trim() : '';
  if (!rawWord) {
    return { ok: false, error: 'La palabra es obligatoria.' };
  }

  if (!DISPLAY_WORD_REGEX.test(rawWord)) {
    return {
      ok: false,
      error:
        'La palabra solo puede contener letras (sin espacios, números ni símbolos).',
    };
  }

  const displayWord = formatDisplayWord(rawWord);
  const normalized = normalizeWord(displayWord);
  if (normalized.length < MIN_WORD_LENGTH || normalized.length > MAX_WORD_LENGTH) {
    return {
      ok: false,
      error: `La palabra debe tener entre ${MIN_WORD_LENGTH} y ${MAX_WORD_LENGTH} letras.`,
    };
  }

  const category =
    typeof input.category === 'string'
      ? input.category.trim().replace(/\s+/g, ' ')
      : '';
  if (!category || category.length > 40) {
    return {
      ok: false,
      error: 'La categoría es obligatoria (máximo 40 caracteres).',
    };
  }

  return {
    ok: true,
    value: {
      word: displayWord,
      normalized,
      category,
      language,
      difficulty,
      points: getPointsForDifficulty(difficulty),
    },
  };
}

function toEntries(rawList: RawWord[], difficulty: WordDifficulty): WordEntry[] {
  const points = getPointsForDifficulty(difficulty);
  return rawList.map((item) => ({
    word: item.word,
    normalized: normalizeWord(item.word),
    category: item.category,
    difficulty,
    points,
  }));
}

export const WORD_BANK: WordBankMap = {
  es: {
    easy: toEntries(ES_EASY, 'easy'),
    hard: toEntries(ES_HARD, 'hard'),
  },
  en: {
    easy: toEntries(EN_EASY, 'easy'),
    hard: toEntries(EN_HARD, 'hard'),
  },
};

const ES_DISTRACTOR_POOL =
  'EEEEEEEEAAAAAAAAOOOOOOOSSSSSSNNNNNNRRRRRIIIIIILLLLLDDDDTTTTCCCCUUUUMPBGVYQHFZJÑX';
const EN_DISTRACTOR_POOL =
  'EEEEEEEEETTTTTTTTAAAAAAAOOOOOOOIIIIIIINNNNNNNSSSSSSRRRRRRHHHHDDDLLLUUUCMFYWGPBVKXQJ';

export function shuffleArray<T>(items: T[], rng: () => number = Math.random): T[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function pickWordPair(
  language: Language,
  usedNormalizedWords: Set<string>,
  rng: () => number = Math.random,
  wordBank: WordBankMap = WORD_BANK
): [WordEntry, WordEntry] {
  const bank = wordBank[language];

  const pickFrom = (list: WordEntry[]): WordEntry => {
    const unused = list.filter((w) => !usedNormalizedWords.has(w.normalized));
    const pool = unused.length > 0 ? unused : list;
    return pool[Math.floor(rng() * pool.length)];
  };

  return [pickFrom(bank.easy), pickFrom(bank.hard)];
}

export function generateScrabbleTiles(
  normalizedWord: string,
  language: Language,
  rng: () => number = Math.random
): ScrabbleTile[] {
  const letters = normalizedWord.split('');
  const pool = language === 'es' ? ES_DISTRACTOR_POOL : EN_DISTRACTOR_POOL;
  const distractorCount = Math.max(0, SCRABBLE_RACK_SIZE - letters.length);

  for (let i = 0; i < distractorCount; i++) {
    const ch = pool[Math.floor(rng() * pool.length)];
    letters.push(ch);
  }

  const shuffled = shuffleArray(letters, rng);
  return shuffled.map((letter, idx) => ({
    id: `tile-${idx}-${letter}`,
    letter,
    eliminated: false,
  }));
}
